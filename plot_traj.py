# Colour map for token labels
TOKEN_COLOURS = {'A': 'tab:blue', 'B': 'tab:orange', 'C': 'tab:green'}

# ----------------------------------------------------------------------
# 2. Plotting helpers --------------------------------------------------
# ----------------------------------------------------------------------
def plot_sequence(coords, tokens, title):
    fig = plt.figure(figsize=(12, 10))
    fig.suptitle(title, fontsize=14, fontweight='bold', y=0.98)  # raise title

    # 3D trajectory plot
    ax3 = fig.add_subplot(2, 2, 1, projection='3d')
    ax3.set_xlabel('1'); ax3.set_ylabel('2'); ax3.set_zlabel('3')
    ax3.set_title('3-D trajectory')

    for i, (pt, tk) in enumerate(zip(coords, tokens)):
        c = TOKEN_COLOURS[tk]
        ax3.scatter(*pt, color=c, s=40)
        if i > 0:
            ax3.plot(
                [coords[i - 1][0], pt[0]],
                [coords[i - 1][1], pt[1]],
                [coords[i - 1][2], pt[2]],
                color='gray', linewidth=1.0
            )
    for tk, c in TOKEN_COLOURS.items():
        ax3.scatter([], [], [], color=c, label=tk)
    ax3.legend(loc='upper left')

    # 2D projections
    ax_xy = fig.add_subplot(2, 2, 2)
    ax_xy.set_xlabel('1'); ax_xy.set_ylabel('2')
    ax_xy.set_title('1 - 2 projection')
    _plot_2d(ax_xy, coords[:, 0], coords[:, 1], tokens)

    ax_yz = fig.add_subplot(2, 2, 3)
    ax_yz.set_xlabel('2'); ax_yz.set_ylabel('3')
    ax_yz.set_title('2 - 3 projection')
    _plot_2d(ax_yz, coords[:, 1], coords[:, 2], tokens)

    ax_xz = fig.add_subplot(2, 2, 4)
    ax_xz.set_xlabel('1'); ax_xz.set_ylabel('3')
    ax_xz.set_title('1 - 3 projection')
    _plot_2d(ax_xz, coords[:, 0], coords[:, 2], tokens)

    fig.tight_layout(rect=[0, 0, 1, 0.95])  # leave space for title
    plt.show()

def _plot_2d(ax, xs, ys, tokens):
    """Helper to scatter and connect points in 2-D."""
    for i, (x, y, tk) in enumerate(zip(xs, ys, tokens)):
        c = TOKEN_COLOURS[tk]
        ax.scatter(x, y, color=c, s=40)
        if i > 0:
            ax.plot([xs[i - 1], x], [ys[i - 1], y],
                    color='gray', linewidth=1.0)


# ----------------------------------------------------------------------
# 3. Driver code -------------------------------------------------------
# ----------------------------------------------------------------------
def main():
    for n, seq in DATA.items():
        # --- Hidden activations ------------------------------------------------
        tokens = [t for t, _, _ in seq]
        hidden = np.array([h for _, h, _ in seq])
        title_h = f'n = {n}   |   hidden activations'
        plot_sequence(hidden, tokens, title_h)

        # --- Context vectors ---------------------------------------------------
        context = np.array([c for _, _, c in seq])
        title_c = f'n = {n}   |   context vectors'
        plot_sequence(context, tokens, title_c)


if __name__ == '__main__':
    main()