import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D  # noqa: F401
import numpy as np

# Token colors: A, B, C
TOKEN_COLOURS = {'A': 'tab:blue', 'B': 'tab:orange', 'C': 'tab:green'}

# Sequence colors for line plot
SEQUENCE_COLOURS = {1: 'red', 2: 'yellow', 3: 'purple', 4: 'brown'}
def plot_all_context_3d(data_dict, save_path=None):
    fig = plt.figure(figsize=(10, 8))
    ax = fig.add_subplot(111, projection='3d')
    fig.suptitle("Context Vector Dynamics (All Cases)", fontsize=14, fontweight='bold', y=0.98)

    # Sequence colors (for line plots)
    SEQUENCE_COLOURS = {1: 'red', 2: 'yellow', 3: 'purple', 4: 'brown'}

    for n in sorted(data_dict):
        seq = data_dict[n]
        coords = np.array([c for _, _, c in seq])
        tokens = [tk for tk, _, _ in seq]

        # Plot trajectory for sequence n
        ax.plot(coords[:, 0], coords[:, 1], coords[:, 2],
                color=SEQUENCE_COLOURS[n], linewidth=2, label=f'n = {n}')

        # Plot each point with color based on token
        for pt, tk in zip(coords, tokens):
            ax.scatter(pt[0], pt[1], pt[2], color=TOKEN_COLOURS[tk],
                       s=40, edgecolor='k', alpha=0.9)

    # Axis labeling
    ax.set_xlabel('1')
    ax.set_ylabel('2')
    ax.set_zlabel('3')

    # Add dummy points for token legend
    for tk, c in TOKEN_COLOURS.items():
        ax.scatter([], [], [], color=c, label=f'{tk}', s=40)

    ax.legend(loc='upper left')
    ax.set_title("3-D Trajectories of Context Vectors")

    if save_path:
        plt.savefig(save_path, dpi=300)
    else:
        plt.show()
    plt.close(fig)

# Call it
plot_all_context_3d(DATA, save_path='all_context_labeled.png')
